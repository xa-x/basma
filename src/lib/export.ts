// Convert hex to CMYK (for print)
export function hexToCmyk(hex: string): { c: number; m: number; y: number; k: number } {
  // Remove # if present
  hex = hex.replace("#", "");

  // Convert to RGB
  const r = parseInt(hex.substring(0, 2), 16) / 255;
  const g = parseInt(hex.substring(2, 4), 16) / 255;
  const b = parseInt(hex.substring(4, 6), 16) / 255;

  // Convert to CMYK
  const k = 1 - Math.max(r, g, b);
  const c = (1 - r - k) / (1 - k) || 0;
  const m = (1 - g - k) / (1 - k) || 0;
  const y = (1 - b - k) / (1 - k) || 0;

  return {
    c: Math.round(c * 100),
    m: Math.round(m * 100),
    y: Math.round(y * 100),
    k: Math.round(k * 100),
  };
}

// Generate ASE color palette (Adobe Swatch Exchange)
export function generateAsePalette(colors: Record<string, string>): string {
  // TODO: Implement actual ASE format
  // For MVP, return text representation
  return Object.entries(colors)
    .map(([name, hex]) => `${name}: ${hex} (CMYK: ${JSON.stringify(hexToCmyk(hex))})`)
    .join("\n");
}
