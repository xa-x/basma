// Export utilities for generating print-ready files

export interface ExportOptions {
  format: "pdf" | "svg" | "png";
  size: "a4" | "letter" | "business-card";
  dpi: 150 | 300 | 600;
  bleed: boolean;
  cropMarks: boolean;
}

export interface BrandKit {
  logo: {
    svg?: string;
    png?: string;
    pdf?: string;
  };
  colors: {
    primary: string;
    secondary: string;
    accent: string;
    neutral: string;
    background: string;
  };
  typography: {
    heading: string;
    body: string;
  };
  businessCard?: {
    front: string;
    back: string;
  };
}

